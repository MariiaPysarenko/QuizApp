package com.quizapp.importing;

/**
 * Цільовий інтерфейс патерну Adapter: будь-яке джерело, з якого можна отримати квіз.
 * <p>
 * Система працює лише з цим інтерфейсом. Кожен зовнішній формат (Google Forms зараз,
 * Google Forms API чи Moodle XML у майбутньому) підключається окремим адаптером.
 */
public interface QuizImport {

    /**
     * Перетворює джерело на квіз-чернетку автора.
     * Запитання, які неможливо імпортувати, не зупиняють імпорт, а потрапляють у звіт.
     */
    ImportResult toQuiz(long creatorId);
}
